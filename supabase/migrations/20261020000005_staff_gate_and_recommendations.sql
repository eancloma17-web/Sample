-- Review-only Department Head and secure staff sign-in rate limits.
-- Apply AFTER 20261020000004_harden_permissions.sql, in staging first.
CREATE TABLE IF NOT EXISTS public.staff_login_rate_limits (
  email_hash text PRIMARY KEY,
  attempts integer NOT NULL DEFAULT 0,
  window_started_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.staff_login_rate_limits ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.staff_login_rate_limits FROM anon, authenticated;

CREATE OR REPLACE FUNCTION public.consume_staff_login_attempt(p_email_hash text)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_count integer;
BEGIN
  IF p_email_hash !~ '^[a-f0-9]{64}$' THEN RETURN false; END IF;
  INSERT INTO public.staff_login_rate_limits(email_hash, attempts, window_started_at)
  VALUES (p_email_hash, 1, now())
  ON CONFLICT (email_hash) DO UPDATE SET
    attempts = CASE WHEN staff_login_rate_limits.window_started_at < now() - interval '15 minutes' THEN 1 ELSE staff_login_rate_limits.attempts + 1 END,
    window_started_at = CASE WHEN staff_login_rate_limits.window_started_at < now() - interval '15 minutes' THEN now() ELSE staff_login_rate_limits.window_started_at END
  RETURNING attempts INTO v_count;
  RETURN v_count <= 5;
END;
$$;
REVOKE ALL ON FUNCTION public.consume_staff_login_attempt(text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.consume_staff_login_attempt(text) TO service_role;

-- Only the Department Head may record recommendations; verified submissions only.
-- Existing decision_records and audit_events are reused; no duplicate table needed.
CREATE OR REPLACE FUNCTION public.record_department_head_recommendation(
  p_supplier_id uuid, p_recommendation text, p_notes text
) RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_profile public.profiles%ROWTYPE; v_status text; v_decision_id uuid;
BEGIN
  SELECT * INTO v_profile FROM public.profiles WHERE id = auth.uid() AND is_active = true;
  IF NOT FOUND OR v_profile.role <> 'CPMD_HEAD' THEN
    RAISE EXCEPTION 'Only the Department Head may record this recommendation';
  END IF;
  IF p_recommendation NOT IN ('RECOMMEND_FOR_FURTHER_REVIEW','RECOMMEND_CORRECTIONS','RECOMMEND_NO_ACTION') THEN
    RAISE EXCEPTION 'Invalid recommendation';
  END IF;
  IF length(trim(coalesce(p_notes,''))) < 5 OR length(p_notes) > 4000 THEN
    RAISE EXCEPTION 'Review remarks must be between 5 and 4000 characters';
  END IF;
  SELECT status INTO v_status FROM public.supplier_applications WHERE id = p_supplier_id FOR UPDATE;
  IF NOT FOUND OR v_status <> 'VERIFIED' THEN
    RAISE EXCEPTION 'Only TSAD-verified submissions may be recommended';
  END IF;
  INSERT INTO public.decision_records(supplier_id,action,performed_by,performed_by_id,role,notes)
  VALUES (p_supplier_id,p_recommendation,v_profile.full_name,auth.uid(),'CPMD_HEAD',trim(p_notes))
  RETURNING id INTO v_decision_id;
  INSERT INTO public.audit_events(actor_id,actor_name,role,action,category,target,metadata)
  VALUES (auth.uid(),v_profile.full_name,'CPMD_HEAD','DEPARTMENT_HEAD_RECOMMENDATION','VERIFICATION',p_supplier_id::text,
    jsonb_build_object('decision_id',v_decision_id,'recommendation',p_recommendation));
  RETURN v_decision_id;
END;
$$;
REVOKE ALL ON FUNCTION public.record_department_head_recommendation(uuid,text,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.record_department_head_recommendation(uuid,text,text) TO authenticated;

-- Do not allow browser clients to forge Department Head decisions directly.
DROP POLICY IF EXISTS "Staff may record own non-final review" ON public.decision_records;
CREATE POLICY "TSAD staff may record own non-final review" ON public.decision_records
FOR INSERT TO authenticated WITH CHECK (
  performed_by_id = auth.uid() AND public.current_user_role() IN ('TSAD_STAFF','CPMD_VERIFIER')
  AND role = public.current_user_role()
  AND action NOT ILIKE '%approv%' AND action NOT ILIKE '%accredit%'
);
-- Keep historic approval data read-only; never manufacture final approvals.

-- Audit entries must be generated by vetted security-definer functions or trusted service roles,
-- never forged directly by browser clients.
DROP POLICY IF EXISTS "System can record audit events" ON public.audit_events;
REVOKE INSERT, UPDATE, DELETE ON public.audit_events FROM anon, authenticated;
